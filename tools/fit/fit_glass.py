"""Measures the glass racetrack of the reference's visualiser as a smooth field over racetrack coordinates and writes
a header with it (default: particles off -> Source/ui/GlassModel.h).

Coordinates: t in [0, 4) around the track (0..1 top straight left->right, 1..2 right end 0..180 deg, 2..3 bottom
straight right->left, 3..4 left end 180..360 deg; angles from up, clockwise) and r = distance from the centre
segment in design px. Stations: 12 per straight (12.5 px apart: the glass barely changes along a straight) and 72 per
end (2.5 deg), each averaged over its width; radial samples every 1 px (the pill on top is drawn separately).

    python tools/fit/fit_glass.py <200 % screenshot> <header> <namespace>
    (particles off: reference/shots/bypassed.png Source/ui/GlassModel.h glassmodel;
     lit: reference/shots/vis_on_median200.png Source/ui/GlassLitModel.h glasslitmodel - the per-pixel median of the
     active frames of a RefCapture film, which removes the sparks)"""
import sys
import numpy as np
from PIL import Image

CX, CY, HL = 367.75, 148.25, 75.25
R0, R1 = 52, 114               # radii sampled (design px)
SEG = [12, 72, 12, 72]         # stations per segment
SUB = 7                        # sub-samples across each station

src = sys.argv[1] if len(sys.argv) > 1 else 'reference/shots/bypassed.png'
out = sys.argv[2] if len(sys.argv) > 2 else 'Source/ui/GlassModel.h'
ns_name = sys.argv[3] if len(sys.argv) > 3 else 'glassmodel'
img = np.asarray(Image.open(src).convert('RGB')).astype(float)


def point(t, r):
    seg = int(np.floor(t)) % 4
    f = t - np.floor(t)
    if seg == 0: return CX - HL + 2 * HL * f, CY - r
    if seg == 2: return CX + HL - 2 * HL * f, CY + r
    a = np.pi * f + (0 if seg == 1 else np.pi)
    ex = CX + HL if seg == 1 else CX - HL
    return ex + r * np.sin(a), CY - r * np.cos(a)


def sample(x, y):
    X, Y = 2 * x - 0.5, 2 * y - 0.5            # bilinear at 200 %
    x0, y0 = int(np.floor(X)), int(np.floor(Y))
    fx, fy = X - x0, Y - y0
    p = img[y0:y0 + 2, x0:x0 + 2]
    return p[0, 0] * (1 - fx) * (1 - fy) + p[0, 1] * fx * (1 - fy) + p[1, 0] * (1 - fx) * fy + p[1, 1] * fx * fy


stations = []                   # (t0, t1) per station
for seg, n in enumerate(SEG):
    for i in range(n): stations.append((seg + i / n, seg + (i + 1) / n))
field = np.zeros((len(stations), R1 - R0 + 1, 3))
for i, (t0, t1) in enumerate(stations):
    for j, r in enumerate(range(R0, R1 + 1)):
        acc = np.zeros(3)
        for s in range(SUB):
            acc += sample(*point(t0 + (t1 - t0) * (s + 0.5) / SUB, r))
        field[i, j] = acc / SUB

field = np.clip(np.round(field), 0, 255).astype(int)
lines = ['// Generated by tools/fit/fit_glass.py from the reference (%s): lighting of the visualiser\'s glass' % src.split('/')[-1],
         '// racetrack over (station, radius), RGB; stations: ' + ', '.join(map(str, SEG)) + ' per segment. See Visualizer.cpp.',
         '#pragma once', '#include <cstdint>', '', f'namespace dp::{ns_name}', '{',
         f'inline constexpr int segStations[4] {{ {", ".join(map(str, SEG))} }};',
         f'inline constexpr int stations = {len(stations)}, r0 = {R0}, r1 = {R1};',
         f'inline constexpr uint8_t rgb[{len(stations)}][{R1 - R0 + 1}][3] {{']
for i in range(len(stations)):
    lines.append('    { ' + ', '.join('{ %d, %d, %d }' % tuple(c) for c in field[i]) + ' },')
lines += ['};', '}', '']
open(out, 'w', newline='\n').write('\n'.join(lines))
print(out, 'stations', len(stations), 'max', field.max())
