"""Measures the shadow the reference's plate knobs cast on the plate (reference/shots/silence.png, 200 %) and writes
Source/ui/KnobShadow.h: the plate's brightness factor (1 = unshadowed) by distance beyond the knob's edge (0..89 design
px, 1 px steps) and angle (36 x 10 deg, from up, clockwise); median over the three knobs, gaps (labels, grille, the
other knobs) filled by interpolation around the angle, then smoothed."""
import numpy as np
from PIL import Image

im = np.asarray(Image.open('reference/shots/silence.png').convert('RGB')).astype(float)
g = im.mean(2)
BASE = 70.0                                   # unshadowed plate grey
knobs = [(45.755, 313.11), (754.745, 313.11), (841.74, 313.11)]
R = 25.06
rs = np.arange(0.0, 90.0, 1.0)
angs = np.radians(np.arange(0, 360, 10))
tab = np.full((3, len(rs), len(angs)), np.nan)
for k, (cx, cy) in enumerate(knobs):
    for i, dr in enumerate(rs):
        for j, a in enumerate(angs):
            x = cx + (R + dr) * np.sin(a); y = cy - (R + dr) * np.cos(a)
            if y < 280 or y > 358.5 or x < 1 or x > 886: continue          # off the plate / its top-edge shading
            if any(ox - 95 < x < ox and abs(y - oy) < 50 for ox, oy in knobs if (ox, oy) != (cx, cy)): continue  # a neighbour's shadow
            if 176 <= x <= 560 and y < 352: continue
            if 268 <= y <= 286 and any(abs(x - lx) < w for lx, w in [(46, 16), (132.25, 8), (636.75, 42), (755, 20), (841.75, 20)]): continue
            if any(np.hypot(x - ox, y - oy) < R + 1.5 for ox, oy in knobs if (ox, oy) != (cx, cy)): continue
            X, Y = int(round(2 * x)), int(round(2 * y))
            tab[k, i, j] = np.median(g[Y - 1:Y + 2, X - 1:X + 2]) / BASE
with np.errstate(all='ignore'):
    med = np.nanmedian(tab, 0)
med[0:2] = np.nan                             # the knob's own rim
med = np.minimum(med, 1.0)
# fill: around the angle per radius, then along the radius
na = len(angs)
for i in range(len(rs)):
    row = med[i]; ok = ~np.isnan(row)
    if ok.sum() >= 3:
        idx = np.arange(na); xs = np.r_[idx[ok] - na, idx[ok], idx[ok] + na]; ys = np.r_[row[ok], row[ok], row[ok]]
        med[i] = np.interp(idx, xs, ys)
for j in range(na):
    col = med[:, j]; ok = ~np.isnan(col)
    med[:, j] = np.interp(rs, rs[ok], col[ok]) if ok.any() else 1.0
# smooth: 3-tap along both axes, and fade to 1 at the far end
for _ in range(2):
    med = (np.roll(med, 1, 1) + 2 * med + np.roll(med, -1, 1)) / 4
    med[1:-1] = (med[:-2] + 2 * med[1:-1] + med[2:]) / 4
med = 1 - (1 - med) * np.clip((89 - rs) / 25, 0, 1)[:, None]
med = np.clip(med, 0, 1)
lines = ['// Generated by tools/fit/fit_knob_shadow.py: shadow of the plate knobs on the plate, measured on the reference.',
         '// factor[d][a]: plate brightness factor at d design px beyond the knob edge, angle a * 10 deg (from up, clockwise).',
         '#pragma once', '', 'namespace dp::knobshadow', '{', f'inline constexpr float factor[{len(rs)}][{na}] {{']
for i in range(len(rs)):
    lines.append('    { ' + ', '.join(f'{v:.3f}f' for v in med[i]) + ' },')
lines += ['};', '}', '']
open('Source/ui/KnobShadow.h', 'w', newline='\n').write('\n'.join(lines))
for i in range(0, 90, 8): print(f'{rs[i]:4.0f}', ' '.join(f'{v:4.2f}' for v in med[i, ::3]))
