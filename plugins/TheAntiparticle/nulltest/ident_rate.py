"""The character section's band filters at other sample rates, from the reference's small-signal impulse responses
at the nine amount nodes (as fit_bands.py at 48 kHz): with the per-band gains known (BandFilters.h bandGain48k),
H = G^T B gives the three band responses B directly. Compared with ours (the same decomposition of our renders).

    python ident_rate.py 44100 [96000 ...]     prints the fit and how far ours is; saves measurements/character/bands_<fs>.npy
    python ident_rate.py --write 44100 88200 96000 192000    Source/dsp/BandFiltersRates.h from the saved ones"""
import os, sys
import numpy as np
import tgp, ident as I

def bands_at(fs, plugin):
    pre = 2 * fs
    L = int(1024 * fs / 48000) + 256
    x = np.zeros(pre + 4 * L, np.float32); x[pre] = 10 ** (-60 / 20)
    ys = tgp.render_many([dict(x=x, norm={**tgp.CHAR_ONLY, 'Character': k / 8}, raw=True) for k in range(9)], plugin, fs=fs, cache=(plugin == 'ref'))
    H = np.array([y[0, pre:pre + L] / 1e-3 for y in ys])
    G = 10 ** (np.array(I.GAINS) / 20)                 # (3, 9)
    B, *_ = np.linalg.lstsq(G.T, H, rcond=None)
    err = np.linalg.norm(G.T @ B - H) / np.linalg.norm(H)
    return B, err

def write(rates):
    lines = ['#pragma once', "// Generated by nulltest/ident_rate.py from the reference: the character section's band filters at other",
             '// sample rates (exact, from its impulse responses; at 1x their delay is the core delay at that rate), and the',
             "// signals the bands' nonlinear stages hear (as NlBandFilters.h). Do not edit by hand.", 'namespace ap::dsp', '{',
             'struct BandFilterSet { double rate; int taps, nlTaps; const double* ir[3]; const double* nl[3]; };']
    sets = []
    for fs in rates:
        B = np.load(os.path.join(tgp.ROOT, 'measurements', 'character', f'bands_{fs}.npy'))
        n = int(np.max(np.where(np.abs(B) > 1e-10)[1])) + 1
        nl = I.nl_firs(int(1024 * fs / 48000), fs, B[:, :n])
        for b in range(3):
            for kind, h in (('ir', B[b, :n]), ('nl', nl[b])):
                lines.append(f'inline constexpr double band{kind.capitalize()}{fs}_{b}[{len(h)}] {{')
                vals = [f'{v:.10g}' for v in h]
                for i in range(0, len(vals), 8): lines.append('    ' + ', '.join(vals[i:i + 8]) + ',')
                lines.append('};')
        sets.append(f'    {{ {fs}.0, {n}, {len(nl[0])}, {{ bandIr{fs}_0, bandIr{fs}_1, bandIr{fs}_2 }}, {{ bandNl{fs}_0, bandNl{fs}_1, bandNl{fs}_2 }} }},')
    lines += [f'inline constexpr BandFilterSet bandFilterSets[{len(sets)}] {{'] + sets + ['};', '}', '']
    open(os.path.join(tgp.PLUGIN, 'Source', 'dsp', 'BandFiltersRates.h'), 'w').write('\n'.join(lines))


if __name__ == '__main__':
    if sys.argv[1] == '--write':
        write([int(a) for a in sys.argv[2:]]); raise SystemExit
    for fs in [int(a) for a in sys.argv[1:]]:
        Br, er = bands_at(fs, 'ref'); Bo, eo = bands_at(fs, 'model')
        np.save(os.path.join(tgp.ROOT, 'measurements', 'character', f'bands_{fs}.npy'), Br)
        print(f'{fs} Hz: rank-3 fit error ref {er:.2e}, ours {eo:.2e}; sum peak at {np.argmax(np.abs(Br.sum(0)))}')
        for b in range(3):
            d = Br[b] - Bo[b]
            print(f'   band {b}: ours vs ref {10*np.log10(np.sum(d**2)/np.sum(Br[b]**2)):7.1f} dB; taps above 1e-7: ref {np.max(np.where(np.abs(Br[b]) > 1e-7)[0]) + 1}')
        F = np.fft.rfftfreq(8192, 1 / fs)
        for f0 in (50, 1000, 5000, 15000, 20000, min(23000, fs / 2 - 500), fs / 2 - 100):
            k = np.argmin(np.abs(F - f0))
            Hr = np.fft.rfft(Br, 8192, axis=1)[:, k]; Ho = np.fft.rfft(Bo, 8192, axis=1)[:, k]
            print(f'   {F[k]:8.0f} Hz  ref ' + ' '.join(f'{20*np.log10(abs(v)+1e-12):7.2f}' for v in Hr) + '   ours ' + ' '.join(f'{20*np.log10(abs(v)+1e-12):7.2f}' for v in Ho))
