"""Writes the trained models (train_gru.py's measurements/scorpius/nn/<case>_gru<hidden>.pt) into
Source/dsp/LearnedModels.h as LearnedWeights (Learned.h).
    python export_models.py <case>=<file.pt> ...      e.g. driveA=drive_a_gru16.pt lift=lift_gru16.pt"""
import os, sys
import numpy as np
import torch
import orion as o

NN = os.path.join(o.ROOT, 'measurements', 'scorpius', 'nn')


def arr(v):
    v = np.asarray(v, np.float32).ravel()
    return '{ ' + ', '.join(f'{x:.9g}f' for x in v) + ' }'


if __name__ == '__main__':
    lines = ['#pragma once', '// Generated by nulltest/export_models.py: the learned modules (Learned.h), trained by nulltest/train_gru.py on',
             '// the reference\'s input and output. Our own weights.', '#include "Learned.h"', 'namespace sc::dsp::models', '{']
    for item in sys.argv[1:]:
        name, file = item.split('=')
        d = torch.load(os.path.join(NN, file))
        s = d['state']; H = d['hidden']
        lines.append(f'inline const LearnedWeights {name} {{ {H}, {arr(s["pre"])},')
        lines.append(f'    {arr(s["post"])},')
        lines.append(f'    {arr(s["gru.weight_ih_l0"])}, {arr(s["gru.weight_hh_l0"])}, {arr(s["gru.bias_ih_l0"])}, {arr(s["gru.bias_hh_l0"])},')
        lines.append(f'    {arr(s["out.weight"])}, {float(s["out.bias"][0]):.9g}f }};')
        print(name, 'hidden', H, 'post taps', len(s['post']))
    lines.append('}')
    open(os.path.join(o.PLUGIN, 'Source', 'dsp', 'LearnedModels.h'), 'w').write('\n'.join(lines) + '\n')
