"""Harmonic EQ: each band's filter at +6 (the band's contribution B6 = H6 - 1 of linear.py's impulse response), as three
biquads in cascade (poles from (fc, Q), free numerators), magnitude and phase from 15 Hz to 22 kHz. Writes
Source/dsp/EqBands.h.
    python fit_eqbands.py"""
import os
import numpy as np
from scipy.optimize import least_squares
import orion as o

NS = 3                     # biquads per band
IR = os.path.join(o.ROOT, 'measurements', 'scorpius', 'ir')
FS = o.FS
f = np.geomspace(15, 22000, 600)
z = np.exp(-2j * np.pi * f / FS)
BANDS = [('40Hz', [30, 60, 20]), ('100Hz', [110, 50, 200]), ('1kHz', [1000, 300, 3000]), ('3kHz', [3000, 1000, 8000]), ('10kHz', [11000, 16000, 5000])]


def measured(name):
    h = np.load(os.path.join(IR, name + '.npy'))[0].astype(np.float64)
    H = np.fft.rfft(h, 1 << 18); fr = np.fft.rfftfreq(1 << 18, 1 / FS)
    return np.interp(f, fr, H.real) + 1j * np.interp(f, fr, H.imag)


def den(fc, q):
    w = 2 * np.pi * fc / FS; a = np.sin(w) / (2 * q); c = np.cos(w)
    return np.array([1.0, -2 * c / (1 + a), (1 - a) / (1 + a)])


def cascade(p):
    H = np.ones_like(z); secs = []
    for s in range(NS):
        fc, q, b0, b1, b2 = p[5 * s:5 * s + 5]
        A = den(fc, q); secs.append(([b0, b1, b2], A.tolist()))
        H = H * (b0 + b1 * z + b2 * z ** 2) / (A[0] + A[1] * z + A[2] * z ** 2)
    return H, secs


def fit(name, guess):
    target = measured(f'eq_{name}_6') - 1
    w = 1 / np.maximum(np.abs(target), 0.02)            # relative error where the band matters, floor elsewhere
    def res(p):
        d = (cascade(p)[0] - target) * np.minimum(w, 20) / 20
        return np.concatenate([d.real, d.imag])
    best = None
    for t in range(16):
        rng = np.random.default_rng(t)
        p0 = []
        for s in range(NS): p0 += [float(np.clip(guess[s % len(guess)] * np.exp(rng.normal(0, 0.3)), 12, 22000)), 0.7 + rng.random(), 0.1, 0, -0.1]
        s_ = least_squares(res, p0, bounds=([10, 0.2, -20, -20, -20] * NS, [23000, 10, 20, 20, 20] * NS), max_nfev=5000)
        if best is None or s_.cost < best.cost: best = s_
    H, secs = cascade(best.x)
    full = 1 + H; m = measured(f'eq_{name}_6')
    err = np.abs(20 * np.log10(np.abs(full) / np.abs(m))); perr = np.abs(np.degrees(np.angle(full / m)))
    return secs, err.max(), perr.max()


if __name__ == '__main__':
    lines = ['#pragma once', '// Generated by nulltest/fit_eqbands.py: each harmonic EQ band\'s filter at +6 (its contribution, before the',
             '// shaper), three biquads in cascade at 48 kHz: { b0, b1, b2, a1, a2 } (a0 = 1).', 'namespace sc::dsp::eqbands', '{',
             'inline constexpr double coeffs[5][3][5] {']
    for name, guess in BANDS:
        secs, e, pe = fit(name, guess)
        print(f'{name:6s} max error {e:.3f} dB, {pe:.2f} deg')
        lines.append('    { ' + ', '.join('{ ' + ', '.join(f'{v:.12g}' for v in (b[0], b[1], b[2], a[1], a[2])) + ' }' for b, a in secs) + ' },   // ' + name)
    lines += ['};', '}']
    out = os.path.join(o.PLUGIN, 'Source', 'dsp', 'EqBands.h'); os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w').write('\n'.join(lines) + '\n')
