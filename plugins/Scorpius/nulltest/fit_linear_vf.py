"""Vector fits of small-signal responses (linear.py's impulse responses) written as parallel sections into
Source/dsp/LinearFits.h, for the linear parts that are not textbook filters.
    python fit_linear_vf.py"""
import os
import numpy as np
import orion as o
from vecfit import fit_sections, parallel_response

FS = 48000
IR = os.path.join(o.ROOT, 'measurements', 'scorpius', 'ir')
f = np.geomspace(8, 23000, 1500); W = 2 * np.pi * f / FS
FITS = [('compWetA', 'comp_a_1.0', 8), ('compWetB', 'comp_b_1.0', 8), ('liftDry', 'lift_0.0', 8), ('liftWet', 'lift_1.0', 10),
        ('driveA', 'drive_a_hp0', 14), ('driveB', 'drive_b_hp0', 14), ('driveC', 'drive_c_hp0', 14),
        ('driveAhp', 'drive_a_hp1', 14), ('driveBhp', 'drive_b_hp1', 14), ('driveChp', 'drive_c_hp1', 14)]

def response(name):
    h = np.load(os.path.join(IR, name + '.npy'))[0].astype(float)
    Hf = np.fft.rfft(h, 1 << 19); fr = np.fft.rfftfreq(1 << 19, 1 / FS)
    return np.interp(f, fr, Hf.real) + 1j * np.interp(f, fr, Hf.imag)

if __name__ == '__main__':
    lines = ['#pragma once', '// Generated by nulltest/fit_linear_vf.py: small-signal responses of the reference as parallel sections at',
             '// 48 kHz, H(z) = d + sum (b0 + b1 z^-1) / (1 + a1 z^-1 + a2 z^-2), from linear.py\'s impulse responses.',
             '#include <vector>', 'namespace sc::dsp::fits', '{', 'struct Parallel { double d; std::vector<std::array<double, 4>> secs; };']
    for key, name, order in FITS:
        H = response(name)
        best = None
        for o_ in (order, order + 2, order - 2):
            d, secs = fit_sections(W, H, o_, 1 / np.maximum(np.abs(H), np.abs(H).max() * 0.01))
            Hm = parallel_response(d, secs, W); m = np.abs(H) > np.abs(H).max() * 0.03
            err = np.abs(20 * np.log10(np.abs(Hm[m]) / np.abs(H[m]))).max()
            stable = all(abs(a2) < 1 and abs(a1) < 1 + a2 for _, _, a1, a2 in secs)
            if stable and (best is None or err < best[0]): best = (err, d, secs, o_)
        err, d, secs, o_ = best
        print(f'{key:10s} order {o_}: max error {err:.3f} dB')
        body = ', '.join('{ ' + ', '.join(f'{v:.17g}' for v in sec) + ' }' for sec in secs)
        lines.append(f'inline const Parallel {key} {{ {d:.17g}, {{ {body} }} }};   // {name}, max error {err:.2f} dB')
    lines += ['}']
    open(os.path.join(o.PLUGIN, 'Source', 'dsp', 'LinearFits.h'), 'w').write('\n'.join(lines).replace('#include <vector>', '#include <array>\n#include <vector>') + '\n')
