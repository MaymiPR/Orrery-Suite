"""Identifies the character section's three band filters from the reference (MEASUREMENTS.md 3.1): the small-signal
impulse responses at the nine amount settings span exactly three fixed FIR filters (661 taps at 48 kHz, peak at
151: the section's crossover is FIR and its latency is the 3.15 ms core delay). Which three is not unique (any mix
of them with matching gains gives the same small-signal sound), so the split is chosen to be closest to the
measured band shapes: Linkwitz-Riley 4th-order magnitudes at 157 / 2676 Hz with linear phase. Writes
Source/dsp/BandFilters.h (the IRs, and the per-band small-signal gains at each amount node) and
measurements/character/bands.json."""
import json, os
import numpy as np
import tgp

FS = tgp.FS
PRE = 2 * FS
L = 1024
NF = 8192
D = 151.27917                       # the core delay at 48 kHz (Source/dsp/Tuning.h coreDelay)
FC1, FC2 = 157.1, 2675.8

if __name__ == '__main__':
    x = np.zeros(PRE + 65536, np.float32); x[PRE] = 10 ** (-60 / 20)
    amounts = [k / 8 for k in range(9)]
    ys = tgp.render_many([dict(x=x, norm={**tgp.CHAR_ONLY, 'Character': a}, raw=True) for a in amounts], cache=True)
    H = np.array([y[0, PRE:PRE + L] / 1e-3 for y in ys]).astype(float)
    U, s, Vt = np.linalg.svd(H, full_matrices=False)
    print('singular values re the first:', np.round(s / s[0], 9))
    V = Vt[:3]
    F = np.fft.rfft(V, NF, axis=1); f = np.fft.rfftfreq(NF, 1 / FS)
    r1, r2 = (f / FC1) ** 4, (f / FC2) ** 4
    targets = [1 / (1 + r1), r1 / (1 + r1) / (1 + r2), r1 / (1 + r1) * r2 / (1 + r2)]
    ph = np.exp(-2j * np.pi * f * D / FS)
    w = np.sqrt(1 / np.maximum(f, 10) * (f < 20000))
    cs = []
    for t in targets:
        A = (F * w).T; y = t * ph * w
        cs.append(np.linalg.lstsq(np.concatenate([A.real, A.imag]), np.concatenate([y.real, y.imag]), rcond=None)[0])
    c0 = np.linalg.lstsq(V.T, H[0], rcond=None)[0]                 # the 0 % response = the sum of the bands
    scale = np.linalg.solve(np.stack(cs, 1), c0)
    B = np.stack([scale[b] * cs[b] @ V for b in range(3)])
    G = np.linalg.lstsq(B.T, H.T, rcond=None)[0]
    err = np.linalg.norm(B.T @ G - H.T) / np.linalg.norm(H)
    n = int(np.max(np.where(np.abs(B) > 1e-9)[1])) + 1
    gains_db = 20 * np.log10(np.abs(G))
    print('taps', n, 'reconstruction error', err, '\nsmall-signal gains dB (low / mid / high) per node:\n', np.round(gains_db, 4))
    lines = ['#pragma once', '// Generated by nulltest/fit_bands.py from the reference: the character section\'s band filters at 48 kHz',
             f'// (FIR, {n} taps, peak at 151) and each band\'s small-signal gain (dB) at amount 0, 25, ..., 200 %.',
             'namespace ap::dsp', '{', f'inline constexpr int bandTaps48k = {n};', f'inline constexpr double bandIr48k[3][{n}] {{']
    for b in range(3):
        vals = [f'{v:.10g}' for v in B[b, :n]]
        lines.append('    {')
        for i in range(0, n, 8): lines.append('        ' + ', '.join(vals[i:i + 8]) + ',')
        lines.append('    },')
    lines += ['};', 'inline constexpr double bandGain48k[3][9] {']
    for b in range(3): lines.append('    { ' + ', '.join(f'{v:.6f}' for v in gains_db[b]) + ' },')
    lines += ['};', '}', '']
    open(os.path.join(tgp.ROOT, 'Source', 'dsp', 'BandFilters.h'), 'w').write('\n'.join(lines))
    json.dump(dict(taps=n, reconstruction_error=float(err), gains_dB=gains_db.round(4).tolist(),
                   singular_values=(s / s[0]).tolist()), open(os.path.join(tgp.ROOT, 'measurements', 'character', 'bands.json'), 'w'), indent=1)
